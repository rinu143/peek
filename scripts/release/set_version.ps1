<#
.SYNOPSIS
    Stamps version across all Peek subprojects: C++ Credential Provider,
    .NET projects (Directory.Build.props), Python Face Engine (engine/_version.py),
    and Inno Setup installer define.

.DESCRIPTION
    Reads SemVer from VERSION (or accepts -Version parameter) and stamps:
    1. credential_provider/version.h (for resources.rc)
    2. Directory.Build.props (Version and InformationalVersion with git commit)
    3. engine/_version.py
    4. installer/version.iss
#>

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$Version
)

$ErrorActionPreference = "Stop"

$RepoRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
if (-not (Test-Path (Join-Path $RepoRoot "VERSION"))) {
    $RepoRoot = (Get-Item $PSScriptRoot).Parent.Parent.FullName
}

$versionFile = Join-Path $RepoRoot "VERSION"

if ([string]::IsNullOrWhiteSpace($Version)) {
    if (-not (Test-Path $versionFile)) {
        throw "VERSION file not found at $versionFile and no -Version parameter was supplied."
    }
    $Version = (Get-Content $versionFile -Raw).Trim()
} else {
    $Version = $Version.Trim()
    Set-Content -Path $versionFile -Value $Version -Encoding utf8
}

# Parse SemVer (e.g. 0.2.0-beta.1 or 1.0.0)
$semVerRegex = '^(?<major>\d+)\.(?<minor>\d+)\.(?<patch>\d+)(?:-(?<prerelease>[0-9A-Za-z.-]+))?(?:\+(?<build>[0-9A-Za-z.-]+))?$'
if ($Version -notmatch $semVerRegex) {
    throw "Version '$Version' does not conform to Semantic Versioning (X.Y.Z[-prerelease][+build])."
}

$major = [int]$Matches['major']
$minor = [int]$Matches['minor']
$patch = [int]$Matches['patch']
$prerelease = $Matches['prerelease']

# Determine git commit hash
$gitCommit = "unknown"
try {
    $gitOutput = git rev-parse --short HEAD 2>$null
    if ($LASTEXITCODE -eq 0 -and -not [string]::IsNullOrWhiteSpace($gitOutput)) {
        $gitCommit = $gitOutput.Trim()
    }
} catch {
    # Git unavailable or not a repo
}

$buildNum = 0
$versionCsv = "$major,$minor,$patch,$buildNum"
$informationalVersion = if ($gitCommit -ne "unknown") { "$Version+$gitCommit" } else { $Version }
$dotnetVersion = "$major.$minor.$patch"

Write-Host "============================================================" -ForegroundColor Cyan
Write-Host "               PEEK VERSION STAMPING PIPELINE               " -ForegroundColor Cyan
Write-Host "============================================================" -ForegroundColor Cyan
Write-Host "[*] Target Version       : $Version" -ForegroundColor Green
Write-Host "[*] SemVer Triple        : $dotnetVersion" -ForegroundColor Gray
Write-Host "[*] Windows CSV Version  : $versionCsv" -ForegroundColor Gray
Write-Host "[*] Git Commit Hash      : $gitCommit" -ForegroundColor Gray
Write-Host "[*] Informational Version: $informationalVersion" -ForegroundColor Gray
Write-Host ""

# 1. Generate credential_provider/version.h
$cpVersionH = Join-Path $RepoRoot "credential_provider\version.h"
$versionHContent = @"
// Auto-generated by scripts/release/set_version.ps1. Do not edit directly.
#pragma once

#define PEEK_VERSION_MAJOR $major
#define PEEK_VERSION_MINOR $minor
#define PEEK_VERSION_PATCH $patch
#define PEEK_VERSION_BUILD $buildNum
#define PEEK_VERSION_STRING "$Version"
#define PEEK_VERSION_WIDE L"$Version"
#define PEEK_VERSION_CSV $versionCsv
"@
Set-Content -Path $cpVersionH -Value $versionHContent -Encoding utf8
Write-Host "[OK] Stamped $cpVersionH" -ForegroundColor Green

# 2. Generate Directory.Build.props at repo root for all .NET projects
$propsFile = Join-Path $RepoRoot "Directory.Build.props"
$propsContent = @"
<Project>
  <PropertyGroup>
    <Version>$dotnetVersion</Version>
    <InformationalVersion>$informationalVersion</InformationalVersion>
  </PropertyGroup>
</Project>
"@
Set-Content -Path $propsFile -Value $propsContent -Encoding utf8
Write-Host "[OK] Stamped $propsFile" -ForegroundColor Green

# 3. Generate engine/_version.py
$pyVersionFile = Join-Path $RepoRoot "engine\_version.py"
$pyVersionContent = @"
# Auto-generated by scripts/release/set_version.ps1. Do not edit directly.
__version__ = "$Version"
__version_info__ = ($major, $minor, $patch)
"@
Set-Content -Path $pyVersionFile -Value $pyVersionContent -Encoding utf8
Write-Host "[OK] Stamped $pyVersionFile" -ForegroundColor Green

# 4. Generate installer/version.iss
$installerDir = Join-Path $RepoRoot "installer"
if (-not (Test-Path $installerDir)) {
    New-Item -ItemType Directory -Path $installerDir -Force | Out-Null
}
$issVersionFile = Join-Path $installerDir "version.iss"
$issVersionContent = @"
; Auto-generated by scripts/release/set_version.ps1. Do not edit directly.
#define MyAppVersion "$Version"
"@
Set-Content -Path $issVersionFile -Value $issVersionContent -Encoding utf8
Write-Host "[OK] Stamped $issVersionFile" -ForegroundColor Green

Write-Host ""
Write-Host "[OK] Successfully stamped version $Version across all subprojects." -ForegroundColor Green
